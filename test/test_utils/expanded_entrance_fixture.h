#ifndef YAZE_TEST_UTILS_EXPANDED_ENTRANCE_FIXTURE_H_
#define YAZE_TEST_UTILS_EXPANDED_ENTRANCE_FIXTURE_H_

#include <algorithm>
#include <cstddef>
#include <cstdint>
#include <initializer_list>
#include <vector>

namespace yaze::test {
// Independent literal bytes from ZScream expandedEntrances.asm / Oracle base
// 2fbf15ae. This installs loader metadata only, never product resolver tables.
inline void InstallExpandedEntranceLoader(std::vector<uint8_t>& data) {
  const auto put = [&](size_t pc, std::initializer_list<uint8_t> bytes) {
    std::copy(bytes.begin(), bytes.end(), data.begin() + pc);
  };
  put(0x7F000, {0x00, 0x01});
  put(0x1599F, {0x22, 0x08, 0xF0, 0x0F});
  put(0x15ACE, {0x22, 0x15, 0xF0, 0x0F});
  put(0x7F008, {0xAA, 0x0A, 0x0A, 0xA8, 0xE2, 0x20, 0xA9, 0x0F, 0x48, 0xAB,
                0xC2, 0x20, 0x6B});
  put(0x7F015, {0x29, 0x0F, 0x85, 0xAA, 0xA9, 0x02, 0x48, 0xAB, 0x6B});
  put(0x159A3, {0xBD, 0x00, 0x80});
  put(0x159AB, {0xBD, 0x00, 0x8C});
  put(0x159B8, {0xBD, 0x00, 0x8A});
  put(0x159CB, {0xBD, 0x00, 0x8E});
  put(0x159D0, {0xBD, 0x00, 0x90});
  put(0x159D5, {0xBD, 0x00, 0x92});
  put(0x159E0, {0xBD, 0x00, 0x94});
  put(0x159F0, {0xBD, 0x00, 0x9D});
  for (int i = 0; i < 8; ++i)
    put(0x15A1A + i * 6, {0xB9, static_cast<uint8_t>(i), 0x82});
  put(0x15A74, {0xBD, 0x00, 0x96});
  put(0x15A7A, {0xBD, 0x00, 0x9F});
  put(0x15A91, {0xBD, 0x00, 0x97});
  put(0x15A96, {0xBD, 0x00, 0x98});
  put(0x15A9C, {0xBD, 0x00, 0x99});
  put(0x15AA1, {0xBD, 0x00, 0x9A});
  put(0x15AAA, {0xBD, 0x00, 0x9A});
  put(0x15AB2, {0xBD, 0x00, 0x9B});
  put(0x15ABB, {0xBD, 0x00, 0x9B});
  put(0x15AC2, {0xBD, 0x00, 0x9C});
  put(0x15ACB, {0xBD, 0x00, 0x9C});
}
}  // namespace yaze::test
#endif
