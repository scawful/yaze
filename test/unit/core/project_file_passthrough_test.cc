  EXPECT_FALSE(project.feature_flags.overworld.kSaveOverworldSprites);
  EXPECT_TRUE(project.feature_flags.overworld.kEnableSpecialWorldExpansion);
  EXPECT_TRUE(project.feature_flags.kSaveWithChangeQueue);
