// A .yaze save must keep what this build does not model: unknown sections,
// unknown keys and comments, in file order. The Oracle of Secrets project file
// (a committed copy, or the live file through YAZE_TEST_ORACLE_PROJECT) must
// survive load + save with only the serializer's intended changes.

